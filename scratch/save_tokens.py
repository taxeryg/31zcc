def main():
    lines = [line.strip() for line in RAW_TOKENS.strip().splitlines() if line.strip() and '|' in line]
    print(f"Total tokens parsed: {len(lines)}")

    # 1. Update discordbot/tokens.json
    discordbot_tokens_path = os.path.join(PROJECT_DIR, 'discordbot', 'tokens.json')
    existing_bot_tokens = []
    if os.path.exists(discordbot_tokens_path):
        try:
            with open(discordbot_tokens_path, 'r', encoding='utf-8') as f:
                existing_bot_tokens = json.load(f)
        except Exception:
            existing_bot_tokens = []
    
    seen = set(existing_bot_tokens)
    added_to_json = 0
    for tok in lines:
        if tok not in seen:
            seen.add(tok)
            existing_bot_tokens.append(tok)
            added_to_json += 1
            
    with open(discordbot_tokens_path, 'w', encoding='utf-8') as f:
        json.dump(existing_bot_tokens, f, ensure_ascii=False, indent=2)
    print(f"Added {added_to_json} tokens to discordbot/tokens.json (Total now: {len(existing_bot_tokens)})")

    # 2. Update Kick accounts DB (storage.py / botdash.db)
    conn = sqlite3.connect(storage.DB_FILE)
    c = conn.cursor()
    c.execute("SELECT token_enc FROM kick_accounts")
    rows = c.fetchall()
    existing_db_tokens = set()
    for r in rows:
        dec = storage.decrypt(r[0])
        clean = dec.replace('Bearer ', '').strip()
        existing_db_tokens.add(clean)

    added_to_db = 0
    for tok in lines:
        if tok not in existing_db_tokens:
            username = tok.split('|')[0]
            token_val = f"Bearer {tok}"
            c.execute("INSERT INTO kick_accounts (username, token_enc) VALUES (?, ?)",
                      (username, storage.encrypt(token_val)))
            existing_db_tokens.add(tok)
            added_to_db += 1
            
    conn.commit()
    conn.close()
    print(f"Added {added_to_db} tokens to website SQLite DB (botdash.db)")

if __name__ == '__main__':
    main()
